def draw_block_nth_ant(font, codepoint, width=None, gap=0.25, rows=2, cols=2):
    global charnames

    if width is None:
        width = font[fontforge.nameFromUnicode(32)].width
    gap = min(width / cols, font.em / rows) * gap

    height = font.em
    charname = charnames[codepoint]
    print(charname)
    if not (match := re.search(r'-(\d+)$', charname)):
        return
    quadrants = match[1]
    quadrants = [int(q) for q in quadrants]
    glyph = font.createChar(codepoint, fontforge.nameFromUnicode(codepoint))
    print("U+%04X" % codepoint)
    glyph.foreground = fontforge.layer() # erase existing content

    for quadrant in quadrants:
        x1 = round(gap/2)
        x2 = round(width/cols - gap/2)
        y1 = round(gap/2)
        y2 = round(font.em/rows - gap/2)
        row = math.floor((quadrant - 1) / cols)
        col = (quadrant - 1) % cols
        x1 += round(width/cols * col)
        x2 += round(width/cols * col)
        y1 += round(font.em/rows * row)
        y2 += round(font.em/rows * row)
        y1 = font.ascent - y1
        y2 = font.ascent - y2
        print("%d: %d,%d %d,%d" % (quadrant, x1, y1, x2, y2))

        pen = glyph.glyphPen(replace=False)
        pen.moveTo((x1,y1))
        pen.lineTo((x2,y1))
        pen.lineTo((x2,y2))
        pen.lineTo((x1,y2))
        pen.closePath()
        glyph.draw(pen)
        pen = None

    glyph.width = width

main()
